#!/usr/bin/env node
/**
 * Writes Mermaid (the build npm ships as `dist/mermaid.min.js`) as a string to `src/components/chat/mermaidHtml.ts`, which the diagram
 * viewer puts in a WebView page. No CDN: the page must work with nothing but the Hermes server reachable. The file is large (about 5 MB)
 * and only loaded when a diagram is opened. Run it after changing the mermaid version and commit the result.
 *
 *   npm run build:mermaid
 */
import { readFileSync, writeFileSync } from 'node:fs'

const version = JSON.parse(readFileSync('node_modules/mermaid/package.json', 'utf8')).version
// A literal "</script" inside the library would end the page's script tag early.
const code = readFileSync('node_modules/mermaid/dist/mermaid.min.js', 'utf8').replace(/<\/script/gi, '<\\/script')

writeFileSync(
  'src/components/chat/mermaidHtml.ts',
  `// Generated by scripts/build-mermaid.mjs from mermaid ${version}. Do not edit.\nexport const MERMAID_VERSION = ${JSON.stringify(version)}\nexport const MERMAID_JS = ${JSON.stringify(code)}\n`,
)
console.log(`wrote src/components/chat/mermaidHtml.ts: mermaid ${version}, ${(code.length / 1024 / 1024).toFixed(1)} MB`)
