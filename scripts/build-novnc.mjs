#!/usr/bin/env node
/**
 * Bundles noVNC and the bridge in `scripts/novnc-entry.js` into one self-contained HTML page and writes it
 * as a string to `src/components/screen/novncHtml.ts`, which the app loads into a WebView. No CDN: the page
 * must work with nothing but the Hermes server reachable. Run it after changing the entry or the noVNC version
 * and commit the result.
 *
 *   npm run build:novnc
 *
 * ESM output is required: noVNC uses top-level await.
 */
import { writeFileSync } from 'node:fs'
import { build } from 'esbuild'

const built = await build({
  entryPoints: ['scripts/novnc-entry.js'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
})

// A literal "</script" inside the bundle would end the tag early.
const code = built.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')

const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html,body{margin:0;height:100%;background:#2B2E34;overflow:hidden;touch-action:none;-webkit-user-select:none;user-select:none}#screen{position:fixed;inset:0}</style>
</head><body><div id="screen"></div><script type="module">${code}</script></body></html>`

const header = `// GENERATED by scripts/build-novnc.mjs (noVNC + the bridge in scripts/novnc-entry.js). Do not edit: run \`npm run build:novnc\`.\n`
writeFileSync('src/components/screen/novncHtml.ts', `${header}export const NOVNC_HTML: string = ${JSON.stringify(html)}\n`)
console.log(`wrote src/components/screen/novncHtml.ts (${Math.round(html.length / 1024)} KB)`)
