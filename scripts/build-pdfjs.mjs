#!/usr/bin/env node
/**
 * Bundles pdf.js (pdfjs-dist, legacy build) and the page in `scripts/pdf-entry.js` into one self-contained HTML page and writes
 * it as a string to `src/components/viewer/pdfHtml.ts`, which the app loads into a WebView. The worker's code is put in the page
 * too (a script tag the page turns into a module worker), so nothing comes from a CDN. Run it after changing the entry or the
 * pdf.js version and commit the result.
 *
 *   npm run build:pdfjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { build } from 'esbuild'

const built = await build({
  entryPoints: ['scripts/pdf-entry.js'],
  bundle: true,
  format: 'esm',
  target: 'es2020',
  minify: true,
  write: false,
  legalComments: 'none',
})

// A literal "</script" inside either script would end its tag early.
const escape = text => text.replace(/<\/script/gi, '<\\/script')
const code = escape(built.outputFiles[0].text)
const worker = escape(readFileSync('node_modules/pdfjs-dist/legacy/build/pdf.worker.min.mjs', 'utf8'))

const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,minimum-scale=1,maximum-scale=5,user-scalable=yes">
<style>html,body{margin:0;padding:0;background:#0A0A0A}#pages{display:flex;flex-direction:column;gap:10px;padding:10px 0 40px}.page{background:#fff;width:100%;position:relative}.page canvas{width:100%;height:100%;display:block}</style>
</head><body><div id="pages"></div>
<script type="text/plain" id="pdf-worker">${worker}</script>
<script type="module">${code}</script></body></html>`

const header = `// GENERATED by scripts/build-pdfjs.mjs (pdf.js ${JSON.parse(readFileSync('node_modules/pdfjs-dist/package.json', 'utf8')).version} + scripts/pdf-entry.js). Do not edit: run \`npm run build:pdfjs\`.\n`
writeFileSync('src/components/viewer/pdfHtml.ts', `${header}export const PDF_HTML: string = ${JSON.stringify(html)}\n`)
console.log(`wrote src/components/viewer/pdfHtml.ts (${Math.round(html.length / 1024)} KB)`)
