#!/usr/bin/env bash
# Hardened container entrypoint for the reviewer-only Blobs demo Hermes server.
# Adapts scripts/demo/demo.sh for Linux Docker (native Bot Screen via Xvnc + Xfce + Chromium,
# offline local plugin install, reverse-proxy trusted_proxies, and zero outbound network access).
set -euo pipefail

REPO="/opt/blobs-demo"
INSTALL="/opt/hermes-agent"
HERMES="$INSTALL/venv/bin/hermes"
PYTHON="$INSTALL/venv/bin/python"
DATA_ROOT="/data"
HOME_DIR="$DATA_ROOT/hermes"
DEMO_WORKSPACE="$DATA_ROOT/workspace"
RUN="$DATA_ROOT/run"
LOGS="$DATA_ROOT/logs"
LOGIN="$DATA_ROOT/login"
RESET_FLAG="$RUN/resetting"
PLUGIN_SRC="file:///opt/hermes-dashboard-plugin"

PORT="${DEMO_PORT:-9219}"
MODEL_PORT="${DEMO_MODEL_PORT:-9220}"
LOCAL_URL="http://127.0.0.1:$PORT"
PUBLIC_URL="${DEMO_PUBLIC_URL:-https://demo.blobs.maddtechnologies.com}"
TRUSTED_PROXIES="${DEMO_TRUSTED_PROXIES:-172.30.0.0/24}"
NODE_FLAGS=(--disable-warning=MODULE_TYPELESS_PACKAGE_JSON)

say() { printf 'demo-container: %s\n' "$*"; }
fail() {
  printf 'demo-container: %s\n' "$*" >&2
  exit 1
}

safe_to_delete() {
  case "$1" in
    "" | / | /data | /data/ | /home | /opt) fail "refusing to delete '$1'" ;;
  esac
}

HERMES_ENV=(env -u HERMES_DESKTOP -u HERMES_DASHBOARD_SESSION_TOKEN -u HERMES_DASHBOARD_PUBLIC_URL
  HERMES_HOME="$HOME_DIR" HERMES_TUI_WS_ORPHAN_REAP_GRACE_S=0 TERMINAL_MAX_FOREGROUND_TIMEOUT=43200
  TERMINAL_LIFETIME_SECONDS=172800 DEMO_HOME="$HOME_DIR")

# ── credentials ──────────────────────────────────────────────────────────────────────────────────

ensure_login() {
  if [ -f "$LOGIN" ]; then
    return
  fi

  local username password secret
  username="${DEMO_USERNAME:-demo}"
  password="${DEMO_PASSWORD:-$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)}"
  secret="${DEMO_AUTH_SECRET:-$(openssl rand -hex 32)}"

  mkdir -p "$DATA_ROOT"
  (
    umask 077
    {
      echo "# Reviewer demo sign-in (generated in container volume, never commit)."
      echo "DEMO_USERNAME=$username"
      echo "DEMO_PASSWORD=$password"
      echo "DEMO_AUTH_SECRET=$secret"
    } >"$LOGIN"
  )
  say "initialized login credentials for user \"$username\" at $LOGIN"
}

login_value() {
  sed -n "s/^$1=//p" "$LOGIN"
}

# ── demo world ───────────────────────────────────────────────────────────────────────────────────

write_workspace() {
  local project="$DEMO_WORKSPACE/storefront"
  safe_to_delete "$DEMO_WORKSPACE"
  mkdir -p "$DEMO_WORKSPACE"
  find "$DEMO_WORKSPACE" -mindepth 1 -maxdepth 1 -exec rm -rf {} +
  cp -R "$REPO/scripts/demo/storefront" "$project"

  git init --quiet --bare "$DEMO_WORKSPACE/storefront.git"
  (
    cd "$project"
    export GIT_AUTHOR_NAME="Storefront Team" GIT_AUTHOR_EMAIL="team@storefront.example" \
      GIT_COMMITTER_NAME="Storefront Team" GIT_COMMITTER_EMAIL="team@storefront.example"
    git init --quiet --initial-branch=main
    git -c commit.gpgsign=false add -A
    git -c commit.gpgsign=false commit --quiet -m "Storefront 1.3.2"
    echo "export const savedCarts = true" >cart.mjs
    git add cart.mjs && git -c commit.gpgsign=false commit --quiet -m "Saved carts"
    echo "export const darkMode = 'system'" >theme.mjs
    git add theme.mjs && git -c commit.gpgsign=false commit --quiet -m "Dark mode"
    echo "export const savedCarts = { sync: true }" >cart.mjs
    git add cart.mjs && git -c commit.gpgsign=false commit --quiet -m "fixup! Saved carts"
    echo "export const darkMode = 'system' // follows the OS" >theme.mjs
    git add theme.mjs && git -c commit.gpgsign=false commit --quiet -m "fixup! Dark mode"
    git remote add origin "$DEMO_WORKSPACE/storefront.git"
    git push --quiet origin main
    GIT_SEQUENCE_EDITOR=true git -c commit.gpgsign=false rebase --quiet -i --autosquash HEAD~4
    git -c commit.gpgsign=false commit --quiet --allow-empty -m "Release 1.4.0"
  )
}

write_config() {
  mkdir -p "$HOME_DIR"
  local hash proxies_yaml="" entry trimmed
  hash="$(DEMO_PASSWORD="$(login_value DEMO_PASSWORD)" "${HERMES_ENV[@]}" "$PYTHON" -I -c '
import os, sys
sys.path.insert(0, sys.argv[1])
from plugins.dashboard_auth.basic import hash_password
print(hash_password(os.environ["DEMO_PASSWORD"]))
' "$INSTALL")"

  IFS=',' read -ra proxy_entries <<<"$TRUSTED_PROXIES"
  for entry in "${proxy_entries[@]}"; do
    trimmed="$(printf '%s' "$entry" | xargs)"
    [ -n "$trimmed" ] && proxies_yaml="${proxies_yaml}    - \"$trimmed\"\n"
  done

  (
    umask 077
    cat >"$HOME_DIR/config.yaml" <<EOF
# Reviewer-only demo Hermes config (generated by entrypoint.sh).
_config_version: 50
model:
  default: hermes-4-405b
  provider: custom
  base_url: http://127.0.0.1:$MODEL_PORT/v1
  api_key: demo-local
  context_length: 131072
agent:
  coding_context: "off"
  clarify_timeout: 0
  session_stall_timeout: 0
  gateway_timeout_warning: 0
approvals:
  mode: manual
  timeout: 2592000
timeouts:
  tools:
    concurrent_batch: 46800
    sequential_call: 46800
terminal:
  backend: local
  cwd: $DEMO_WORKSPACE/storefront
  timeout: 300
bot_desktop:
  placement: gateway
  geometry: 1280x800
  idle_stop_minutes: 0
  min_free_memory_mb: 0
memory:
  memory_enabled: false
  user_profile_enabled: false
  nudge_interval: 0
auxiliary:
  title_generation:
    enabled: false
  background_review:
    enabled: false
curator:
  enabled: false
dashboard:
  public_url: $PUBLIC_URL
  trusted_proxies:
$(printf '%b' "$proxies_yaml")  basic_auth:
    username: $(login_value DEMO_USERNAME)
    password_hash: "$hash"
    secret: $(login_value DEMO_AUTH_SECRET)
    session_ttl_seconds: 2592000
EOF
  )
}

# ── process supervision ──────────────────────────────────────────────────────────────────────────

pid_alive() {
  local file="$RUN/$1.pid"
  [ -f "$file" ] && kill -0 "$(cat "$file")" 2>/dev/null
}

start_process() {
  local name="$1"
  shift
  mkdir -p "$RUN" "$LOGS"
  if pid_alive "$name"; then
    return
  fi
  nohup "$PYTHON" -I -c 'import os, sys; os.setsid(); os.execvp(sys.argv[1], sys.argv[1:])' "$@" >>"$LOGS/$name.log" 2>&1 &
  echo $! >"$RUN/$name.pid"
  disown $!
}

stop_process() {
  local name="$1" file="$RUN/$1.pid"
  [ -f "$file" ] || return 0
  local pid
  pid="$(cat "$file")"
  if kill -0 "$pid" 2>/dev/null; then
    kill -TERM -- "-$pid" 2>/dev/null || kill "$pid" 2>/dev/null || true
    for _ in $(seq 1 150); do
      kill -0 "$pid" 2>/dev/null || break
      sleep 0.1
    done
    kill -KILL -- "-$pid" 2>/dev/null || true
    say "stopped $name"
  fi
  rm -f "$file"
}

wait_for_server() {
  for _ in $(seq 1 240); do
    if curl -fsS -o /dev/null "$LOCAL_URL/api/status" 2>/dev/null; then
      return 0
    fi
    pid_alive dashboard || fail "the dashboard exited; see $LOGS/dashboard.log"
    sleep 0.5
  done
  fail "the dashboard did not answer on $LOCAL_URL; see $LOGS/dashboard.log"
}

start_servers() {
  start_process model env DEMO_LLM_PORT="$MODEL_PORT" DEMO_WORKSPACE="$DEMO_WORKSPACE" DEMO_LLM_LOG="$LOGS/model-requests.jsonl" \
    node "$REPO/scripts/demo/demo-llm.mjs"
  cd "$DATA_ROOT"
  start_process gateway "${HERMES_ENV[@]}" "$HERMES" gateway run --quiet
  start_process dashboard "${HERMES_ENV[@]}" "$HERMES" dashboard --host 0.0.0.0 --port "$PORT" --no-open --skip-build
  cd - >/dev/null
  wait_for_server
}

stop_all() {
  stop_process dashboard
  stop_process gateway
  stop_process model
  pkill -f "scripts/test.mjs --browsers" 2>/dev/null || true
  pkill -TERM Xvnc 2>/dev/null || true
}

install_plugin() {
  local scope=()
  [ -n "${1:-}" ] && scope=(-p "$1")
  "${HERMES_ENV[@]}" "$HERMES" ${scope[@]+"${scope[@]}"} plugins install "$PLUGIN_SRC" --force --enable >>"$LOGS/setup.log" 2>&1 ||
    fail "installing hermes-dashboard${1:+ for $1} failed; see $LOGS/setup.log"
  say "installed hermes-dashboard${1:+ for $1}"
}

configure_scout_screen() {
  local setting
  for setting in \
    "terminal.backend=local" \
    "terminal.cwd=$DEMO_WORKSPACE/storefront" \
    "bot_desktop.placement=gateway" \
    "bot_desktop.geometry=1280x800" \
    "bot_desktop.idle_stop_minutes=0" \
    "bot_desktop.min_free_memory_mb=0"; do
    "${HERMES_ENV[@]}" "$HERMES" -p scout config set "${setting%%=*}" "${setting#*=}" >>"$LOGS/setup.log" 2>&1 ||
      fail "setting Scout's ${setting%%=*} failed; see $LOGS/setup.log"
  done
  say "configured Scout's native Linux Bot Screen"
}

seed_step() {
  DEMO_URL="$LOCAL_URL" DEMO_LOGIN="$LOGIN" DEMO_GATEWAY_SCREEN=1 \
    node "${NODE_FLAGS[@]}" "$REPO/scripts/demo/seed.ts" "$1"
}

build_world() {
  mkdir -p "$LOGS" "$RUN"
  write_workspace
  write_config
  install_plugin
  start_servers
  say "creating the five bots"
  seed_step bots
  configure_scout_screen
  for bot in courier scout forge; do
    install_plugin "$bot"
  done
  stop_all
  start_servers
  say "filling the dashboards"
  for pair in courier:requests scout:scout forge:forge; do
    "${HERMES_ENV[@]}" "$PYTHON" -I "$REPO/scripts/demo/seed_dashboard.py" \
      "$HOME_DIR/profiles/${pair%%:*}/plugins/hermes-dashboard" \
      "${pair%%:*}" "$REPO/scripts/demo/dashboard-${pair#*:}.json"
  done
  say "seeding chats, routine, room, and Scout's screen"
  seed_step world
}

reset_world() {
  mkdir -p "$RUN"
  : >"$RESET_FLAG"
  trap 'rm -f "$RESET_FLAG"' RETURN
  stop_all
  ensure_login
  safe_to_delete "$HOME_DIR"
  rm -rf "$HOME_DIR" "$LOGS"
  build_world
  rm -f "$RESET_FLAG"
  trap - RETURN
  say "reset complete; ready at $PUBLIC_URL"
}

# ── commands ─────────────────────────────────────────────────────────────────────────────────────

cmd_serve() {
  ensure_login
  if [ "${DEMO_RESET_ON_START:-0}" = "1" ] || [ ! -f "$HOME_DIR/config.yaml" ]; then
    reset_world
  else
    start_servers
    if ! seed_step status; then
      say "seeded live states are missing after restart; rebuilding demo world"
      reset_world
    fi
  fi

  local exiting=0
  on_signal() {
    exiting=1
    say "shutting down"
    stop_all
    exit 0
  }
  trap on_signal TERM INT

  say "serving on $LOCAL_URL (public URL: $PUBLIC_URL)"
  while [ "$exiting" -eq 0 ]; do
    if [ -f "$RESET_FLAG" ]; then
      sleep 1
      continue
    fi
    for name in model gateway dashboard; do
      if ! pid_alive "$name"; then
        [ -f "$RESET_FLAG" ] && break
        fail "$name process died unexpectedly; check $LOGS/$name.log"
      fi
    done
    sleep 5
  done
}

cmd_password() {
  [ -f "$LOGIN" ] || fail "no login yet (start the container first)"
  printf 'URL:      %s\n' "$PUBLIC_URL"
  printf 'Username: %s\n' "$(login_value DEMO_USERNAME)"
  printf 'Password: %s\n' "$(login_value DEMO_PASSWORD)"
}

case "${1:-serve}" in
  serve) cmd_serve ;;
  reset) reset_world ;;
  status) seed_step status ;;
  password) cmd_password ;;
  *)
    echo "usage: entrypoint.sh [serve|reset|status|password]" >&2
    exit 2
    ;;
esac
